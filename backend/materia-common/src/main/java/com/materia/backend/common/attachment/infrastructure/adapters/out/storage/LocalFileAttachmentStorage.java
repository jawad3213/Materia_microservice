package com.materia.backend.common.attachment.infrastructure.adapters.out.storage;

import com.materia.backend.common.attachment.domain.exceptions.AttachmentStorageException;
import com.materia.backend.common.attachment.domain.ports.out.AttachmentStorage;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;

/**
 * Keeps attachments as files under app.attachments.storage-dir. On EC2 that directory is /data/attachments, on the
 * same snapshotted EBS volume as the database. Each file is written to a temporary name and moved into place, so a
 * reader never sees half a file.
 */
@Component
public class LocalFileAttachmentStorage implements AttachmentStorage {

    private final Path root;

    public LocalFileAttachmentStorage(@Value("${app.attachments.storage-dir:data/attachments}") String storageDir) {
        this.root = Path.of(storageDir).toAbsolutePath().normalize();
    }

    @Override
    public void store(String key, byte[] content) {
        Path target = resolve(key);
        try {
            Files.createDirectories(target.getParent());
            Path tmp = Files.createTempFile(target.getParent(), ".upload-", ".tmp");
            try {
                Files.write(tmp, content);
                Files.move(tmp, target, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING);
            } finally {
                Files.deleteIfExists(tmp);
            }
        } catch (IOException e) {
            throw new AttachmentStorageException("Could not save the attachment", e);
        }
    }

    @Override
    public byte[] read(String key) {
        try {
            return Files.readAllBytes(resolve(key));
        } catch (IOException e) {
            throw new AttachmentStorageException("Could not read the attachment", e);
        }
    }

    @Override
    public void delete(String key) {
        try {
            Files.deleteIfExists(resolve(key));
        } catch (IOException e) {
            throw new AttachmentStorageException("Could not remove the attachment", e);
        }
    }

    /** Keys are generated by AttachmentService; this guard still refuses any key that would leave the root. */
    private Path resolve(String key) {
        Path path = root.resolve(key).normalize();
        if (!path.startsWith(root)) {
            throw new IllegalArgumentException("Invalid attachment key");
        }
        return path;
    }
}
