package com.materia.backend.infrastructure.storage;

import com.materia.backend.common.attachment.domain.exceptions.AttachmentStorageException;
import com.materia.backend.common.attachment.domain.ports.out.AttachmentStorage;
import software.amazon.awssdk.core.exception.SdkException;
import software.amazon.awssdk.core.sync.RequestBody;
import software.amazon.awssdk.services.s3.S3Client;
import software.amazon.awssdk.services.s3.model.DeleteObjectRequest;
import software.amazon.awssdk.services.s3.model.GetObjectRequest;
import software.amazon.awssdk.services.s3.model.PutObjectRequest;

import java.util.Arrays;

/**
 * Keeps attachments as objects in an S3 bucket, under this service's prefix ({@code procurement/},
 * {@code finance/}...): the services can share a bucket, each in its own part of it, as each owns its schema in the
 * database. An object is written whole or not at all, so a reader never sees half a file. Encryption at rest is the
 * bucket's (S3 encrypts every new object with SSE-S3 by default); no header asks for it, so S3-compatible servers
 * without a key service work too. Chosen with {@code app.attachments.storage=s3} (S3AttachmentStorageConfig).
 */
public class S3AttachmentStorage implements AttachmentStorage {

    private final S3Client s3;
    private final String bucket;
    private final String prefix;

    public S3AttachmentStorage(S3Client s3, String bucket, String prefix) {
        if (bucket == null || bucket.isBlank()) {
            throw new IllegalStateException("app.attachments.s3.bucket is not set");
        }
        this.s3 = s3;
        this.bucket = bucket.trim();
        this.prefix = normalizePrefix(prefix);
    }

    @Override
    public void store(String key, byte[] content) {
        String objectKey = objectKey(key);
        try {
            s3.putObject(PutObjectRequest.builder().bucket(bucket).key(objectKey).build(), RequestBody.fromBytes(content));
        } catch (SdkException e) {
            throw new AttachmentStorageException("Could not save the attachment", e);
        }
    }

    @Override
    public byte[] read(String key) {
        String objectKey = objectKey(key);
        try {
            return s3.getObjectAsBytes(GetObjectRequest.builder().bucket(bucket).key(objectKey).build()).asByteArray();
        } catch (SdkException e) {
            throw new AttachmentStorageException("Could not read the attachment", e);
        }
    }

    /** Removing an object that is not there succeeds, as removing a missing file does. */
    @Override
    public void delete(String key) {
        String objectKey = objectKey(key);
        try {
            s3.deleteObject(DeleteObjectRequest.builder().bucket(bucket).key(objectKey).build());
        } catch (SdkException e) {
            throw new AttachmentStorageException("Could not remove the attachment", e);
        }
    }

    /**
     * Keys are generated by AttachmentService ({@code purchase_order/<owner id>/<id>.pdf}); this guard still refuses a
     * key that would leave this service's prefix or that S3 would read differently than a file system.
     */
    private String objectKey(String key) {
        if (key == null || key.isBlank() || key.startsWith("/") || key.contains("\\")
                || Arrays.stream(key.split("/", -1)).anyMatch(part -> part.isEmpty() || part.equals(".") || part.equals(".."))) {
            throw new IllegalArgumentException("Invalid attachment key");
        }
        return prefix + key;
    }

    private static String normalizePrefix(String prefix) {
        if (prefix == null) return "";
        String trimmed = prefix.trim().replaceAll("^/+", "").replaceAll("/+$", "");
        return trimmed.isEmpty() ? "" : trimmed + "/";
    }
}
